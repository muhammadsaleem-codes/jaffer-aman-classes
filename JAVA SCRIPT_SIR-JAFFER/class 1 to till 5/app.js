// # JavaScript Exponentiation (`**`)

// ### 1. What is Exponentiation?

// Exponentiation ka matlab hai kisi number ko baar-baar usi number se multiply karna.

// JavaScript mein `**` exponentiation operator hai.

// **Syntax:**
// ```javascript
// base ** exponent
// ```

// - **Base:** Woh number jise multiply karna hai.
// - **Exponent:** Batata hai ke base ke kitne factors multiply karne hain.

// ### 2. Example: `2 ** 4`

// ```javascript
// console.log(2 ** 4);

// // Output: 16
// ```

// Step by step:

// ```javascript
// 2 * 2 = 4
// 4 * 2 = 8
// 8 * 2 = 16
// ```

// Is liye `2 ** 4 = 16`.

// ### 3. More Examples

// ```javascript
// 2 ** 2  // 4
// 2 ** 3  // 8
// 2 ** 4  // 16

// 3 ** 2  // 9
// 3 ** 3  // 27

// 4 ** 2  // 16
// 4 ** 3  // 64
// 4 ** 4  // 256
// ```

// ### 4. Important Rule

// `3 ** 2` ka matlab:

// ```javascript
// 3 * 3 = 9
// ```

// `4 ** 4` ka matlab:

// ```javascript
// 4 * 4 * 4 * 4 = 256
// ```

// **Remember:**

// - `+` means Addition
// - `*` means Multiplication
// - `**` means Exponentiation

// ### 5. Practice

